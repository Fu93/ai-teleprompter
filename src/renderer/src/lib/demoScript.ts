/**
 * demoScript.ts — 內建範例講稿(單一出處)。
 *
 * ── 為什麼要有這份東西 ──
 *   這個產品的門面是提詞浮層,而浮層需要「一份有內容的講稿」才會出現:
 *   空稿刻意不開浮層(見 Dashboard.launchScript 的說明)。於是全新使用者
 *   下載完這個 App 之後,必須先自己寫出一段稿子、存檔,才第一次看到它。
 *
 *   這與 preflight.ts / onboarding.ts 檔頭寫的「不擋只想看看浮層長什麼樣的人」
 *   直接衝突 —— 不擋路的代價不該是「看不到」。所以空狀態直接給一顆
 *   「載入範例講稿並試提詞」:一鍵建立 → 開浮層,三十秒內看到成品。
 *
 * ── 為什麼是這一份內容 ──
 *   **內容**與 scripts/capture-ui.mjs 和除錯面板「載入範例稿」同一份
 *   (兩者都改吃這個模組的 DEMO_SCRIPT_CONTENT)。三處各寫一份一定會漂移,
 *   而漂移的症狀是「稽核截圖上的浮層」與「使用者第一次看到的浮層」不是同一個
 *   東西 —— 那麼所有視覺稽核的結論都不再適用於首用體驗。
 *
 *   標題故意**不**共用:截圖那條路用的是「產品發表 · 開場」(它是一個示範用的
 *   場合名),而使用者自己的第一份稿叫什麼不該被那個名字綁住。會影響版面的
 *   是內容長度,不是標題,所以共用的必須是內容。
 *
 * ── 為什麼內容要空行 ──
 *   空行是 bullet(重點要點)模式的段落切分依據,也是逐句模式的句子來源。
 *   範例稿如果是一整塊文字,四種顯示模式裡有兩種會直接顯示「此講稿無法切出重點」
 *   —— 使用者第一次看到浮層就會以為那是壞的。
 */
